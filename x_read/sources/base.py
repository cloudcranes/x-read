from typing import Protocol
from x_read.models import Book, ChapterContent, Directory, SearchResult


class BookSource(Protocol):
    provider: str

    async def search(self, query: str, cursor: str | None = None) -> SearchResult: ...
    async def get_book(self, book_id: str) -> Book: ...
    async def get_chapters(self, book_id: str) -> Directory: ...
    async def get_chapter(self, book_id: str, chapter_id: str) -> ChapterContent: ...
